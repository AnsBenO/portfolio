function readInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'en';
  }

  const storedLocale = localStorage.getItem(STORAGE_KEY);
  return SUPPORTED_LOCALES.find((locale) => locale === storedLocale) ?? 'en';
}

@Injectable({ providedIn: 'root' })
export class LocalizationService {
  private readonly document = inject(DOCUMENT);

  readonly locale = signal<Locale>(readInitialLocale());
  readonly direction = computed(() => (this.locale() === 'ar' ? 'rtl' : 'ltr'));
  readonly localeOptions = LOCALE_OPTIONS;

  constructor() {
    this.syncDocumentLanguage();
  }

  setLocale(locale: Locale): void {
    localStorage.setItem(STORAGE_KEY, locale);
    this.locale.set(locale);
    this.syncDocumentLanguage();
  }

  text(key: TranslationKey, parameters: Record<string, string | number> = {}): string {
    return TRANSLATIONS[this.locale()][key].replace(
      /\{(\w+)\}/g,
      (_placeholder, name: string) => String(parameters[name] ?? ''),
    );
  }

  private syncDocumentLanguage(): void {
    this.document.documentElement.lang = this.locale();
    this.document.documentElement.dir = this.direction();
  }
}
